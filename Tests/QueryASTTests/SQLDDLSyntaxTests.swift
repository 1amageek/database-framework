import DatabaseKit
import QueryAST
import Testing

@Suite("SQL schema definition syntax")
struct SQLDDLSyntaxTests {
    @Test("Schema create rename and multi-drop preserve exact names and policy")
    func schemas() throws {
        try roundTrips([
            "CREATE SCHEMA IF NOT EXISTS \"App\"",
            "ALTER SCHEMA \"App\" RENAME TO \"Store\"",
            "DROP SCHEMA IF EXISTS app, archive CASCADE",
        ])
        #expect(try SQLParser().parse("CREATE SCHEMA app") == .ddl(.createSchema(name: "app", ifNotExists: false)))
    }

    @Test("Table definitions preserve types constraints and generation policy")
    func tableDefinitions() throws {
        try roundTrips([
            "CREATE TABLE IF NOT EXISTS app.items (id BIGSERIAL PRIMARY KEY, name TEXT NOT NULL, score NUMERIC(12, 2) DEFAULT 0, CONSTRAINT positive CHECK (score >= 0), UNIQUE NULLS NOT DISTINCT (name))",
            "CREATE TABLE child (id INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 5 INCREMENT BY 2 NO MAXVALUE), parent_id BIGINT CONSTRAINT parent_reference REFERENCES app.parent (id) MATCH FULL ON DELETE SET NULL (parent_id) ON UPDATE CASCADE DEFERRABLE INITIALLY DEFERRED, doubled BIGINT GENERATED ALWAYS AS (parent_id * 2) STORED)",
            "CREATE TABLE generated (a INT GENERATED BY DEFAULT AS IDENTITY, b SMALLSERIAL, c INT GENERATED ALWAYS AS (a + 1) VIRTUAL, CONSTRAINT pk PRIMARY KEY (a) DEFERRABLE INITIALLY IMMEDIATE)",
            "CREATE TABLE edges (a INT, b INT, FOREIGN KEY (a, b) REFERENCES parent MATCH SIMPLE ON UPDATE RESTRICT ON DELETE SET DEFAULT)",
        ])
        guard case .ddl(.createTable(let table)) = try SQLParser().parse("CREATE TEMP TABLE t (id INT)") else { Issue.record("Expected table"); return }
        #expect(table.temporary)
        #expect(table.name == TableRef("t"))
        guard case .ddl(.createTable(let definitions)) = try SQLParser().parse("CREATE TABLE t (id SERIAL, n INT DEFAULT :n, g INT GENERATED ALWAYS AS (n + 1) STORED, i BIGINT GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY 3))"),
              case .columns(let columns, _) = definitions.source else { Issue.record("Expected column definitions"); return }
        #expect(columns[0].type == .integer)
        #expect(columns[0].policy == .serial)
        #expect(columns[1].policy == .input(defaultExpression: .parameter(.name("n"))))
        guard case .generated(_, let stored) = columns[2].policy else { Issue.record("Expected generated expression"); return }
        #expect(stored)
        #expect(columns[3].policy == .identity(generation: .byDefault, options: SQLSequenceOptions(increment: 3)))
    }

    @Test("CTAS preserves inferred and explicit names temporary scope and data mode")
    func tableAsQuery() throws {
        try roundTrips([
            "CREATE TABLE app.snapshot AS SELECT id, name FROM app.items WITH NO DATA",
            "CREATE TEMPORARY TABLE snapshot (item_id, title) AS SELECT id, name FROM items WITH DATA",
            "CREATE TABLE snapshot AS WITH q AS (SELECT 1 AS id) SELECT id FROM q",
        ])
        guard case .ddl(.createTable(let value)) = try SQLParser().parse("CREATE TABLE t AS SELECT :id AS id WITH NO DATA"),
              case .query(_, let columns, let withData) = value.source else { Issue.record("Expected CTAS"); return }
        #expect(columns == nil)
        #expect(!withData)
    }

    @Test("ALTER TABLE preserves every ordered action")
    func alterTable() throws {
        try roundTrips([
            "ALTER TABLE IF EXISTS app.items ADD COLUMN IF NOT EXISTS score INT DEFAULT 1, ADD CONSTRAINT nonnegative CHECK (score >= 0), ALTER COLUMN score TYPE BIGINT USING score + 1, ALTER COLUMN score SET DEFAULT 2, ALTER COLUMN score DROP DEFAULT, ALTER COLUMN score SET NOT NULL, ALTER COLUMN score DROP NOT NULL, DROP CONSTRAINT IF EXISTS nonnegative CASCADE, DROP COLUMN IF EXISTS old RESTRICT",
            "ALTER TABLE app.items ALTER score SET DATA TYPE BIGINT USING CAST(score AS BIGINT)",
            "ALTER TABLE app.items RENAME COLUMN name TO title",
            "ALTER TABLE app.items RENAME TO products",
        ])
        guard case .ddl(.alterTable(let alter)) = try SQLParser().parse("ALTER TABLE IF EXISTS t ADD a INT, ALTER a SET DEFAULT :value, DROP b CASCADE") else { Issue.record("Expected ALTER TABLE"); return }
        #expect(alter.ifExists)
        #expect(alter.actions.count == 3)
        #expect(alter.actions[1] == .setDefault(column: "a", expression: .parameter(.name("value"))))
        #expect(alter.actions[2] == .dropColumn(name: "b", ifExists: false, behavior: .cascade))
    }

    @Test("Composite expression partial and unique index keys retain sort metadata")
    func indexes() throws {
        try roundTrips([
            "CREATE INDEX IF NOT EXISTS item_order ON app.items (score DESC NULLS LAST, id ASC)",
            "CREATE UNIQUE INDEX item_name ON items ((lower(name)), id) NULLS NOT DISTINCT WHERE score > 0",
            "DROP INDEX IF EXISTS item_order, item_name CASCADE",
        ])
        guard case .ddl(.createIndex(let index)) = try SQLParser().parse("CREATE UNIQUE INDEX ix ON t (a DESC NULLS FIRST, b) WHERE b > :minimum") else { Issue.record("Expected index"); return }
        #expect(index.unique)
        #expect(index.keys.count == 2)
        #expect(index.keys[0].direction == .descending)
        #expect(index.keys[0].nulls == .first)
    }

    @Test("Views preserve replacement explicit columns CTEs and qualified targets")
    func views() throws {
        try roundTrips([
            "CREATE VIEW app.names AS SELECT id, name FROM app.items",
            "CREATE OR REPLACE VIEW app.names (item_id, title) AS WITH q AS (SELECT id, name FROM items) SELECT id, name FROM q",
            "DROP VIEW IF EXISTS app.names, app.old_names RESTRICT",
        ])
    }

    @Test("Materialized view creation refresh and drop preserve data mode")
    func materializedViews() throws {
        try roundTrips([
            "CREATE MATERIALIZED VIEW IF NOT EXISTS app.totals (total) AS SELECT count(*) FROM items WITH NO DATA",
            "CREATE MATERIALIZED VIEW totals AS SELECT 1 AS n WITH DATA",
            "REFRESH MATERIALIZED VIEW app.totals WITH NO DATA",
            "REFRESH MATERIALIZED VIEW totals",
            "DROP MATERIALIZED VIEW IF EXISTS app.totals CASCADE",
        ])
    }

    @Test("Sequences preserve every option restart rename and ownership distinction")
    func sequences() throws {
        try roundTrips([
            "CREATE SEQUENCE IF NOT EXISTS app.ids AS BIGINT START WITH -5 INCREMENT BY -2 MINVALUE -100 MAXVALUE -1 CYCLE OWNED BY app.items.id",
            "CREATE SEQUENCE ids NO MINVALUE NO MAXVALUE NO CYCLE OWNED BY NONE",
            "CREATE SEQUENCE edge START WITH -9223372036854775808 MAXVALUE 9223372036854775807",
            "ALTER SEQUENCE IF EXISTS app.ids AS INTEGER START WITH 1 INCREMENT BY 3 NO MINVALUE MAXVALUE 100 NO CYCLE RESTART WITH 9 OWNED BY items.id",
            "ALTER SEQUENCE ids RESTART",
            "ALTER SEQUENCE ids RENAME TO next_ids",
            "ALTER SEQUENCE ids OWNED BY NONE",
            "DROP SEQUENCE IF EXISTS app.ids, next_ids CASCADE",
        ])
        guard case .ddl(.createSequence(let created)) = try SQLParser().parse("CREATE SEQUENCE s NO MINVALUE NO MAXVALUE NO CYCLE OWNED BY NONE"),
              case .ddl(.alterSequence(let altered)) = try SQLParser().parse("ALTER SEQUENCE s RESTART WITH -2 OWNED BY app.t.id") else { Issue.record("Expected sequence declarations"); return }
        #expect(created.options.minimum == .some(.none))
        #expect(created.options.maximum == .some(.none))
        #expect(created.options.cycle == false)
        #expect(created.ownedBy == .some(.none))
        #expect(altered.restart == .value(-2))
        #expect(altered.ownedBy == .column(table: TableRef(schema: "app", table: "t"), column: "id"))
    }

    @Test("Malformed unsupported and duplicate DDL clauses fail explicitly")
    func failures() throws {
        for sql in [
            "CREATE TABLE t (id INT DEFAULT 1 DEFAULT 2)",
            "CREATE TABLE t (id INT GENERATED BY DEFAULT AS (1) STORED)",
            "CREATE TABLE t (id INT NOT NULL DEFERRABLE INITIALLY DEFERRED)",
            "CREATE SEQUENCE s START WITH 1 START WITH 2",
            "CREATE SEQUENCE s MINVALUE 1 NO MINVALUE",
            "CREATE SEQUENCE s INCREMENT BY 0",
            "CREATE SEQUENCE s START WITH 9223372036854775808",
            "ALTER SEQUENCE s",
            "ALTER TABLE t ALTER a SET DATA BIGINT",
            "CREATE TABLE t (id INT, id INT)",
            "CREATE INDEX i ON t ()",
            "CREATE INDEX app.i ON app.t (a)",
            "CREATE UNIQUE INDEX i ON t (a) INCLUDE (b)",
            "CREATE OR REPLACE MATERIALIZED VIEW m AS SELECT 1",
            "REFRESH MATERIALIZED VIEW CONCURRENTLY m",
            "CREATE VIEW v AS SELECT 1 WITH CHECK OPTION",
            "DROP TABLE t CASCADE extra",
        ] {
            #expect(throws: (any Error).self) { _ = try SQLParser().parse(sql) }
        }
    }

    @Test("DDL source capture retains repeated expression and nested query occurrences")
    func sourceCapture() throws {
        let sql = "CREATE TABLE t (a INT DEFAULT :same CHECK (a > :same), b INT GENERATED ALWAYS AS (a + :same) STORED, CHECK (b > :same))"
        let parsed = try SQLParser().parseWithSource(sql)
        let first = try #require(parsed.occurrences.child(of: parsed.root, field: .ddlColumn, index: 0))
        let second = try #require(parsed.occurrences.child(of: parsed.root, field: .ddlColumn, index: 1))
        let defaultValue = try #require(parsed.occurrences.child(of: first, field: .ddlDefault))
        let generated = try #require(parsed.occurrences.child(of: second, field: .ddlGenerated))
        let constraint = try #require(parsed.occurrences.child(of: parsed.root, field: .ddlConstraint, index: 0))
        _ = try #require(parsed.occurrences.child(of: constraint, field: .ddlCheck))
        #expect(defaultValue != generated)
        #expect(parsed.sourceMap[defaultValue]?.range.start != parsed.sourceMap[generated]?.range.start)
        for sql in [
            "CREATE TABLE t AS SELECT :same AS n",
            "CREATE VIEW v AS SELECT :same AS n",
            "CREATE MATERIALIZED VIEW m AS SELECT :same AS n WITH NO DATA",
        ] {
            let captured = try SQLParser().parseWithSource(sql)
            let query = try #require(captured.occurrences.child(of: captured.root, field: .ddlQuery))
            _ = try #require(captured.occurrences.child(of: query, field: .projection, index: 0))
        }
        let index = try SQLParser().parseWithSource("CREATE INDEX i ON t (a + :same, b + :same) WHERE a > :same")
        for ordinal in UInt32(0)..<2 {
            let key = try #require(index.occurrences.child(of: index.root, field: .ddlIndexKey, index: ordinal))
            _ = try #require(index.occurrences.child(of: key, field: .operand))
        }
        _ = try #require(index.occurrences.child(of: index.root, field: .ddlIndexPredicate))
        _ = try SQLParser().parseStatementsWithSource("CREATE SCHEMA app; ALTER SCHEMA app RENAME TO store; DROP SCHEMA store")
        for sql in [
            "ALTER TABLE t ADD c INT DEFAULT :same, ALTER a TYPE BIGINT USING a + :same, ALTER b SET DEFAULT :same",
            "CREATE SEQUENCE s AS BIGINT OWNED BY t.a",
            "DROP TABLE a, b CASCADE",
        ] { _ = try SQLParser().parseWithSource(sql) }
    }

    @Test("DDL output and structural collection boundaries reject one-past limits")
    func limits() throws {
        let statement = QueryStatement.ddl(.createSchema(name: "x", ifNotExists: false))
        let expected = try SQLSerializer().serialize(statement)
        let exact = QueryStructuralLimits(maximumRetainedBytes: UInt64(expected.utf8.count))
        #expect(try SQLSerializer(limits: exact).serialize(statement) == expected)
        let short = QueryStructuralLimits(maximumRetainedBytes: UInt64(expected.utf8.count - 1))
        #expect(throws: SQLSerializationError.self) { _ = try SQLSerializer(limits: short).serialize(statement) }
        let narrow = QueryStructuralLimits(maximumCollectionElements: 1)
        #expect(throws: QueryStructuralValidationError.self) { _ = try SQLParser(structuralLimits: narrow).parse("DROP TABLE a, b") }
        let malformed = QueryStatement.ddl(.createTable(SQLCreateTable(name: TableRef("t"), source: .columns([
            SQLColumnDefinition(name: "id", type: .text, policy: .serial),
        ], constraints: []))))
        #expect(throws: SQLSerializationError.self) { _ = try SQLSerializer().serialize(malformed) }
    }

    @Test("PROPERTY GRAPH retains its existing CREATE and DROP branch")
    func propertyGraphs() throws {
        let drop = try SQLParser().parse("DROP PROPERTY GRAPH g")
        #expect(drop == .dropGraph("g"))
        let create = try SQLParser().parse("CREATE PROPERTY GRAPH g VERTEX TABLES (people KEY (id))")
        guard case .createGraph = create else { Issue.record("Expected property graph"); return }
        #expect(try SQLParser().parse(SQLSerializer().serialize(create)) == create)
    }

    private func roundTrips(_ statements: [String]) throws {
        for sql in statements {
            let statement = try SQLParser().parse(sql)
            let emitted = try SQLSerializer().serialize(statement)
            #expect(try SQLParser().parse(emitted) == statement, "Round trip: \(sql) -> \(emitted)")
            #expect(try SQLParser().parseWithSource(sql).statement == statement)
            #expect(try SQLSerializer().serialize(SQLParser().parse(emitted)) == emitted)
        }
    }
}
